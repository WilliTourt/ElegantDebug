#define INFO_TYPE_PLAIN     "[INFO] "
#define OK_TYPE_PLAIN       "[OK] "
#define SUCCESS_TYPE_PLAIN  "[SUCCESS] "

/************************************************************************/



// tick provider (User must feed from timer ISR)
extern volatile uint32_t _debug_tick_ms;



// Initialize the library; MUST be called before other functions.
// Baud rate is generated by Timer 1 (mode 2), assumes an 11.0592 MHz crystal.
// A 1 ms Timer 0 interrupt is also configured; define an ISR that calls
// debug_tick() to make timestamps work.
void debug_init(unsigned long baud, bool enable_timestamp, bool enable_color, bool enable_filename_line);

// Keil C51 does not support the C99 `inline` keyword, so debug_tick() is a macro.
#define debug_tick()  (_debug_tick_ms++)

// Basic formatted log
void debug_log(const char* format, ...);

// Log with a type prefix
void debug_logWithType(const char* type, const char* style, const char* format, ...);

// Convenience helpers
void debug_ok(const char* format, ...);
void debug_success(const char* format, ...);
void debug_info(const char* format, ...);

// Variants that accept file and line:
// NOTE: debug_error_fileline / debug_warning_fileline are NOT provided on
// 8051. Without __VA_ARGS__ there is no way to reach them through macros,
// and their local variable frames would overflow the 256-byte pdata page
// (together with the printf library) in the Compact memory model.
// Use debug_error() / debug_warning() instead.

// Runtime setters
void debug_setTimestampEnabled(bool enabled);
void debug_setColorEnabled(bool enabled);
// Enable/disable showing filename:line when using the file/line variants or macros
void debug_setFilenameLineEnabled(bool enabled);

// helper functions generating ANSI escape sequences for variable 24-bit colors
// they return a pointer to a static string which remains valid until the
// next call. This allows using them inside printf/format strings just like
// the `COLOR_CUSTOM`/`BG_COLOR_CUSTOM` macros but with runtime values.
const char* customTextColor(uint8_t r, uint8_t g, uint8_t b);
const char* customBgColor(uint8_t r, uint8_t g, uint8_t b);

// Keil C51 does not support __VA_ARGS__ variadic macros, so debug_error /
// debug_warning are plain functions: they cannot automatically include the
// caller's file/line on 8051. Use debug_error_fileline() explicitly if you
// want file:line in the output.
void debug_error(const char* format, ...);
void debug_warning(const char* format, ...);



#endif // __ELEGANT_DEBUG_H
